//! Serialization and the built-in neutral sRGB baseline.

use std::time::{SystemTime, UNIX_EPOCH};

use super::parser::{Profile, Tag, HEADER_LEN};

fn s15f16(v: f64) -> [u8; 4] {
    ((v * 65536.0).round() as i32).to_be_bytes()
}

fn xyz_tag(x: f64, y: f64, z: f64) -> Vec<u8> {
    let mut d = b"XYZ \0\0\0\0".to_vec();
    for v in [x, y, z] {
        d.extend_from_slice(&s15f16(v));
    }
    d
}

fn text_tag(s: &str) -> Vec<u8> {
    let mut d = b"text\0\0\0\0".to_vec();
    d.extend_from_slice(s.as_bytes());
    d.push(0);
    d
}

/// v2 `textDescriptionType`.
fn desc_tag(s: &str) -> Vec<u8> {
    let mut d = b"desc\0\0\0\0".to_vec();
    d.extend_from_slice(&((s.len() + 1) as u32).to_be_bytes());
    d.extend_from_slice(s.as_bytes());
    d.push(0);
    d.extend_from_slice(&[0u8; 4 + 4 + 2 + 1 + 67]); // no unicode / scriptcode text
    d
}

/// sRGB electro-optical transfer function as a 1024-entry `curv` table.
fn srgb_curve() -> Vec<u8> {
    const N: usize = 1024;
    let mut d = b"curv\0\0\0\0".to_vec();
    d.extend_from_slice(&(N as u32).to_be_bytes());
    for i in 0..N {
        let v = i as f64 / (N - 1) as f64;
        let lin = if v <= 0.04045 {
            v / 12.92
        } else {
            ((v + 0.055) / 1.055).powf(2.4)
        };
        d.extend_from_slice(&((lin * 65535.0).round() as u16).to_be_bytes());
    }
    d
}

/// (year, month, day, hour, minute, second) in UTC.
fn now_utc() -> [u16; 6] {
    let secs = SystemTime::now()
        .duration_since(UNIX_EPOCH)
        .map(|d| d.as_secs() as i64)
        .unwrap_or(0);
    let days = secs.div_euclid(86_400);
    let rem = secs.rem_euclid(86_400);
    // Howard Hinnant's civil_from_days.
    let z = days + 719_468;
    let era = z.div_euclid(146_097);
    let doe = z.rem_euclid(146_097);
    let yoe = (doe - doe / 1460 + doe / 36_524 - doe / 146_096) / 365;
    let y = yoe + era * 400;
    let doy = doe - (365 * yoe + yoe / 4 - yoe / 100);
    let mp = (5 * doy + 2) / 153;
    let d = doy - (153 * mp + 2) / 5 + 1;
    let m = if mp < 10 { mp + 3 } else { mp - 9 };
    let y = if m <= 2 { y + 1 } else { y };
    [
        y as u16,
        m as u16,
        d as u16,
        (rem / 3600) as u16,
        (rem % 3600 / 60) as u16,
        (rem % 60) as u16,
    ]
}

impl Profile {
    /// A neutral sRGB display profile (D50-adapted colorants, sRGB transfer
    /// curve). Used when the display has no ICC profile of its own, so the
    /// only effect of the generated profile is its `vcgt` curves.
    pub fn default_srgb() -> Profile {
        let mut h = [0u8; HEADER_LEN];
        h[8..12].copy_from_slice(&0x0240_0000u32.to_be_bytes()); // v2.4
        h[12..16].copy_from_slice(b"mntr");
        h[16..20].copy_from_slice(b"RGB ");
        h[20..24].copy_from_slice(b"XYZ ");
        for (i, v) in now_utc().iter().enumerate() {
            h[24 + 2 * i..26 + 2 * i].copy_from_slice(&v.to_be_bytes());
        }
        h[36..40].copy_from_slice(b"acsp");
        // 64..68 rendering intent = 0 (perceptual)
        for (i, v) in [0.9642, 1.0, 0.8249].iter().enumerate() {
            h[68 + 4 * i..72 + 4 * i].copy_from_slice(&s15f16(*v));
        }
        h[80..84].copy_from_slice(b"gmpn");

        let curve = srgb_curve();
        let blobs = vec![
            desc_tag("ns-gammactl sRGB baseline"), // 0
            text_tag("Generated by ns-gammactl. No copyright."), // 1
            xyz_tag(0.9642, 1.0, 0.8249),          // 2
            xyz_tag(0.4360, 0.2225, 0.0139),       // 3
            xyz_tag(0.3851, 0.7169, 0.0971),       // 4
            xyz_tag(0.1431, 0.0606, 0.7141),       // 5
            curve,                                 // 6 (shared by r/g/b TRC)
        ];
        let tag = |sig: &[u8; 4], blob| Tag { sig: *sig, blob };
        let tags = vec![
            tag(b"desc", 0),
            tag(b"cprt", 1),
            tag(b"wtpt", 2),
            tag(b"rXYZ", 3),
            tag(b"gXYZ", 4),
            tag(b"bXYZ", 5),
            tag(b"rTRC", 6),
            tag(b"gTRC", 6),
            tag(b"bTRC", 6),
        ];
        Profile { header: h, tags, blobs }
    }

    /// Serialize with freshly computed offsets, sizes and 4-byte alignment.
    /// Tags that shared data keep sharing it; unreferenced data is dropped.
    pub fn to_bytes(&self) -> Vec<u8> {
        let n = self.tags.len();
        let table_len = 4 + 12 * n;
        let mut body: Vec<u8> = Vec::new();
        let mut placed: Vec<Option<(usize, usize)>> = vec![None; self.blobs.len()];
        let mut table: Vec<u8> = Vec::with_capacity(table_len);
        table.extend_from_slice(&(n as u32).to_be_bytes());

        let data_start = HEADER_LEN + table_len;
        for t in &self.tags {
            let (off, len) = *placed[t.blob].get_or_insert_with(|| {
                let off = data_start + body.len();
                let data = &self.blobs[t.blob];
                body.extend_from_slice(data);
                while body.len() % 4 != 0 {
                    body.push(0);
                }
                (off, data.len())
            });
            table.extend_from_slice(&t.sig);
            table.extend_from_slice(&(off as u32).to_be_bytes());
            table.extend_from_slice(&(len as u32).to_be_bytes());
        }

        let total = data_start + body.len();
        let mut header = self.header;
        header[0..4].copy_from_slice(&(total as u32).to_be_bytes());
        header[84..100].fill(0); // profile ID is no longer valid; 0 = not computed

        let mut out = Vec::with_capacity(total);
        out.extend_from_slice(&header);
        out.extend_from_slice(&table);
        out.extend_from_slice(&body);
        out
    }
}
